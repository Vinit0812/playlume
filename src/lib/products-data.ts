// Helper: get unique categories
export function getCategories(): string[] {
  return [...new Set(MASTER_PRODUCTS.map((p) => p.category))];
}

// Helper: get subcategories for a category
export function getSubCategories(category: string): string[] {
  return [
    ...new Set(
      MASTER_PRODUCTS.filter((p) => p.category === category).map(
        (p) => p.subCategory
      )
    ),
  ];
}

// Helper: get products by category slug
export function getProductsByCategorySlug(slug: string): MasterProduct[] {
  return MASTER_PRODUCTS.filter((p) => p.categorySlug === slug);
}

