// Helper: get unique categories
export function getCategories(): string[] {
  return [...new Set(MASTER_PRODUCTS.map((p) => p.category))];
}

// Helper: get subcategories for a category
export function getSubCategories(category: string): string[] {
  return [
    ...new Set(
      MASTER_PRODUCTS.filter((p) => p.category === category).map(
        (p) => p.subCategory
      )
    ),
  ];
}

// Helper: get products by category slug
export function getProductsByCategorySlug(slug: string): MasterProduct[] {
  return MASTER_PRODUCTS.filter((p) => p.categorySlug === slug);
}

// Helper: get products by subcategory slug
export function getProductsBySubCategorySlug(slug: string): MasterProduct[] {
  return MASTER_PRODUCTS.filter((p) => p.subCategorySlug === slug);
}

// Helper: get product by slug
export function getProductBySlug(slug: string): MasterProduct | undefined {
  return MASTER_PRODUCTS.find((p) => p.slug === slug || p.id === slug || (p.aliases && p.aliases.includes(slug)));
}

// Helper: find product by id or slug
export function findProductByIdOrSlug(idOrSlug: string): MasterProduct | undefined {
  return MASTER_PRODUCTS.find(
    (p) =>
      p.slug === idOrSlug ||
      p.id === idOrSlug ||
      (p.aliases && p.aliases.includes(idOrSlug)) ||
      (p.variantItems && p.variantItems.some((v) => v.id === idOrSlug || v.sku === idOrSlug))
  );
}

// Helper: search products
export function searchProducts(query: string, categorySlug?: string): MasterProduct[] {
  const q = query.toLowerCase();
  return MASTER_PRODUCTS.filter((p) => {
    const matchesQuery =
      p.name.toLowerCase().includes(q) ||
      p.category.toLowerCase().includes(q) ||
      p.subCategory.toLowerCase().includes(q) ||
      p.tags.some((t) => t.toLowerCase().includes(q)) ||
      (p.variantItems && p.variantItems.some((v) => v.label.toLowerCase().includes(q) || Object.values(v.attributes).some(attr => attr.toLowerCase().includes(q)))) ||
      (p.variants && p.variants.some((v) => v.value.toLowerCase().includes(q)));
    const matchesCat = !categorySlug || categorySlug === "all" || p.categorySlug === categorySlug;
    return matchesQuery && matchesCat;
  });
}

// Helper: get related products
export function getRelatedProducts(productOrId: MasterProduct | string, limit = 5): MasterProduct[] {
  const prod = typeof productOrId === "string" ? findProductByIdOrSlug(productOrId) : productOrId;
  if (!prod) return MASTER_PRODUCTS.slice(0, limit);
  return MASTER_PRODUCTS.filter(
    (p) =>
      p.id !== prod.id &&
      (p.categorySlug === prod.categorySlug ||
        p.subCategorySlug === prod.subCategorySlug)
  ).slice(0, limit);
}

